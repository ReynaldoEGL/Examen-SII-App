create table if not exists public.subjects (
  id                 bigint generated by default as identity primary key,
  code               varchar(30)  not null unique,
  name               varchar(180) not null,
  credits            smallint     not null check (credits between 1 and 20),
  theory_hours       smallint     not null default 0 check (theory_hours >= 0),
  practice_hours     smallint     not null default 0 check (practice_hours >= 0),
  suggested_semester smallint     not null check (suggested_semester between 1 and 20),
  difficulty         smallint     not null default 3 check (difficulty between 1 and 5), -- la asigna el admin
  is_specialty       boolean      not null default false,
  min_credit_percent numeric(5,2) check (min_credit_percent between 0 and 100),         -- % de créditos para poder cursarla
  active             boolean      not null default true,
  created_at         timestamptz  not null default now(),
  updated_at         timestamptz  not null default now()
);
create index if not exists subjects_semester_idx on public.subjects (suggested_semester);

-- Fila (subject_id = X, related_subject_id = Y):
--   'prerequisite' -> X requiere Y aprobada.
--   'corequisite'  -> X requiere Y aprobada o cursada en el mismo periodo.
create table if not exists public.subject_relations (
  id                 bigint generated by default as identity primary key,
  subject_id         bigint      not null references public.subjects(id) on delete cascade,
  related_subject_id bigint      not null references public.subjects(id) on delete cascade,
  relation_type      varchar(12) not null check (relation_type in ('prerequisite','corequisite')),
  created_at         timestamptz not null default now(),
  check (subject_id <> related_subject_id),
  unique (subject_id, related_subject_id)
);
create index if not exists subject_relations_related_idx on public.subject_relations (related_subject_id);

-- Servicio social, actividades complementarias, residencias y lengua extranjera.
