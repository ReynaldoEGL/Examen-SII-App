-- Tras cada login conserva solo las N sesiones más recientes de esa persona.
-- N sale de academic_rules (max_sessions_per_student / max_sessions_per_admin).
create or replace function public.enforce_session_limit()
returns trigger
language plpgsql
as $$
declare
  max_sessions integer;
begin
  -- Serializa los logins de la misma persona para que dos solicitudes
  -- simultáneas no rebasen el máximo por una carrera entre transacciones.
  perform pg_advisory_xact_lock(
    hashtextextended(new.principal_type || ':' || new.principal_id, 0)
  );

  select greatest(1, least(10, coalesce(
           (select (r.value #>> '{}')::integer
              from public.academic_rules r
             where r.rule_key = case new.principal_type
                                  when 'student' then 'max_sessions_per_student'
                                  else 'max_sessions_per_admin'
                               end),
           case new.principal_type when 'student' then 3 else 2 end
         )))
    into max_sessions;

  delete from public.app_sessions s
   where s.principal_type = new.principal_type
     and s.principal_id   = new.principal_id
     and s.id not in (
           select k.id
             from public.app_sessions k
            where k.principal_type = new.principal_type
              and k.principal_id   = new.principal_id
            order by k.created_at desc, k.id desc
            limit max_sessions
         );
  return null;
end;
$$;

drop trigger if exists app_sessions_limit_trg on public.app_sessions;
create trigger app_sessions_limit_trg
  after insert on public.app_sessions
  for each row execute function public.enforce_session_limit();

-- Borra sesiones vencidas o inactivas (session_idle_hours). Devuelve cuántas borró.
create or replace function public.purge_expired_sessions()
returns integer
language plpgsql
as $$
declare
  idle_hours integer;
  removed    integer;
begin
  select greatest(1, least(720, coalesce(
           (select (r.value #>> '{}')::integer from public.academic_rules r where r.rule_key = 'session_idle_hours'),
           12
         )))
    into idle_hours;

  delete from public.app_sessions
   where expires_at < now()
      or coalesce(last_used_at, created_at) < now() - make_interval(hours => idle_hours);

  get diagnostics removed = row_count;
  return removed;
end;
$$;

-- Si se desactiva o elimina un admin, se cierran sus sesiones.
create or replace function public.revoke_admin_sessions()
returns trigger
language plpgsql
as $$
begin
  delete from public.app_sessions
   where principal_type = 'admin' and principal_id = old.id::text;
  return null;
end;
$$;

drop trigger if exists admins_revoke_on_delete  on public.admins;
drop trigger if exists admins_revoke_on_disable on public.admins;
create trigger admins_revoke_on_delete
  after delete on public.admins
  for each row execute function public.revoke_admin_sessions();
create trigger admins_revoke_on_disable
  after update of active on public.admins
  for each row when (new.active = false)
  execute function public.revoke_admin_sessions();

