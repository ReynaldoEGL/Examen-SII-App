-- Alumno: principal_id = HMAC-SHA256 hex (64 caracteres) del número de control; nunca el número.
-- Admin:  principal_id = id del administrador (texto).
-- token_hash = SHA-256 del valor de la cookie. sii_token = JWT del SII ya cifrado por Laravel.
create table if not exists public.app_sessions (
  id             bigint generated by default as identity primary key,
  principal_type varchar(10) not null check (principal_type in ('student','admin')),
  principal_id   varchar(64) not null,
  token_hash     char(64)    not null unique,
  sii_token      text,
  expires_at     timestamptz not null,
  last_used_at   timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint app_sessions_principal_chk check (
    (principal_type = 'student' and principal_id ~ '^[0-9a-f]{64}$' and sii_token is not null)
    or (principal_type = 'admin' and principal_id ~ '^[0-9]+$')
  )
);
create index if not exists app_sessions_expires_idx   on public.app_sessions (expires_at);
create index if not exists app_sessions_principal_idx on public.app_sessions (principal_type, principal_id, created_at desc);

