-- Detiene el script si alguna clave no existe en subjects.
do $$
begin
  if exists (
    select 1
      from _relations_seed v
      left join public.subjects s on s.code = v.code
      left join public.subjects r on r.code = v.related_code
     where s.id is null or r.id is null
  ) then
    raise exception 'Hay claves en las relaciones que no existen en subjects.';
  end if;
end $$;

insert into public.subject_relations (subject_id, related_subject_id, relation_type)
select s.id, r.id, v.relation_type
  from _relations_seed v
  join public.subjects s on s.code = v.code
  join public.subjects r on r.code = v.related_code
on conflict (subject_id, related_subject_id) do nothing;

-- Detiene el script si los prerrequisitos forman un ciclo.
do $$
begin
  if exists (
    with recursive walk (current_id, visited, is_cycle) as (
      select r.related_subject_id,
             array[r.subject_id],
             r.related_subject_id = r.subject_id
        from public.subject_relations r
       where r.relation_type = 'prerequisite'
      union all
      select r.related_subject_id,
             w.visited || w.current_id,
             r.related_subject_id = any (w.visited || w.current_id)
        from walk w
        join public.subject_relations r
          on r.subject_id = w.current_id and r.relation_type = 'prerequisite'
       where not w.is_cycle
    )
    select 1 from walk where is_cycle
  ) then
    raise exception 'Los prerrequisitos forman un ciclo.';
  end if;
end $$;

-- ---------------------------------------------------------------------
-- 8. SEGURIDAD: RLS en todas las tablas de ESTA aplicación, sin acceso público.
--    No se modifican tablas ajenas que pudieran existir en el esquema public.
--    Laravel se conecta con un rol backend privilegiado; RLS no lo protege de
--    una filtración de sus credenciales.
-- ---------------------------------------------------------------------

do $$
declare
  t text;
  app_tables text[] := array[
    'subjects', 'subject_relations', 'milestones', 'load_rules', 'academic_rules',
    'periods', 'sections', 'section_meetings', 'admins', 'app_sessions',
    'audit_logs', 'cache', 'cache_locks'
  ];
begin
  foreach t in array app_tables loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon, authenticated', t);
  end loop;

  -- Revoca también los permisos de secuencias identity pertenecientes a las
  -- tablas de esta aplicación, sin tocar secuencias de otras tablas públicas.
  for t in
    select seq.relname
      from pg_class seq
      join pg_namespace ns on ns.oid = seq.relnamespace
      join pg_depend dep on dep.objid = seq.oid and dep.deptype in ('a', 'i')
      join pg_class tbl on tbl.oid = dep.refobjid
     where ns.nspname = 'public'
       and seq.relkind = 'S'
       and tbl.relname = any(app_tables)
  loop
    execute format('revoke all on sequence public.%I from anon, authenticated', t);
  end loop;
end $$;

revoke execute on function public.enforce_session_limit() from public, anon, authenticated;
revoke execute on function public.purge_expired_sessions() from public, anon, authenticated;
revoke execute on function public.revoke_admin_sessions() from public, anon, authenticated;

commit;

